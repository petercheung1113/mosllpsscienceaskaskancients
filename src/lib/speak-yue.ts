function withTone(text: string): string {
  const parts = text.split(/(?<=[。！？])/).filter((part) => part.trim());
  if (!parts.length) return text;
  return parts
    .map((part, index) => {
      const last = index === parts.length - 1;
      if (/[？呀啦喎㗎]$/.test(part.trim()) || part.includes("？")) {
        return part.replace(/？/g, "呀？");
      }
      if (last && part.endsWith("。")) return part.replace(/。$/, "啦。");
      if (part.endsWith("。")) return part.replace(/。$/, "呀。");
      return part;
    })
    .join("");
}
