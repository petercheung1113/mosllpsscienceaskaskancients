type Entry = { q: string; answer: string; who?: CharacterId };

function expand(topic: Topic): Entry[] {
  const questions = [...FRAMES.map((frame) => frame(topic.stem)), ...(topic.extra ?? [])];
  return questions.map((q) => ({ q, answer: topic.answer, who: topic.who }));
}

export const CAMP_ENTRIES: Entry[] = [...TOPICS, ...moreTopics()].flatMap(expand);

export const CAMP_QUESTION_COUNT = CAMP_ENTRIES.length;

function fold(value: string): string {
  return value.toLowerCase().replace(/[\s\u200b，。！？、,.!?:：；;「」"'‘’]/g, "");
}

export function matchCampLife(
  id: CharacterId,
  question: string,
  person: { name: string; method: string; problem: string },
): string | null {
  const text = fold(question);
  if (text.length < 2) return null;
  let best: { score: number; answer: string } | null = null;
  for (const entry of CAMP_ENTRIES) {
    if (entry.who && entry.who !== id) continue;
    const key = fold(entry.q);
    if (key.length < 2) continue;
    let score = 0;
    if (text.includes(key)) score = key.length + (entry.who === id ? 20 : 0);
    if (score > 0 && (!best || score > best.score)) best = { score, answer: entry.answer };
  }
  if (!best) return null;
  return best.answer
    .replaceAll("{name}", person.name)
    .replaceAll("{method}", person.method)
    .replaceAll("{problem}", person.problem);
}
